function baseTheme(
  partial: Partial<BookTheme> & Pick<BookTheme, 'id' | 'name'>,
): BookTheme {
  return {
    ...defaults,
    ...partial,
    chapterHeading: { ...defaults.chapterHeading, ...partial.chapterHeading },
    paragraph: { ...defaults.paragraph, ...partial.paragraph },
    subheading: { ...defaults.subheading, ...partial.subheading },
    sceneBreak: { ...defaults.sceneBreak, ...partial.sceneBreak },
    specialBlocks: { ...defaults.specialBlocks, ...partial.specialBlocks },
    notes: { ...defaults.notes, ...partial.notes },
    print: { ...defaults.print, ...partial.print },
    typography: { ...defaults.typography, ...partial.typography },
    headerFooter: { ...defaults.headerFooter, ...partial.headerFooter },
  }
}

