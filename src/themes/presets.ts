export function cloneTheme(theme: BookTheme, name: string): BookTheme {
  return {
    ...structuredClone(baseTheme(theme)),
    id: `theme-${crypto.randomUUID()}`,
    name,
    preset: false,
    favorite: false,
  }
}

export function getThemeById(themes: BookTheme[], id: string): BookTheme {
  const found = themes.find((t) => t.id === id) ?? themes[0] ?? PRESET_THEMES[0]
  return baseTheme(found)
}

